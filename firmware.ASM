; DELAY DE 5us
DELAY_I2C
	BANK1
	MOVLW	B'00000001'
	MOVWF	OPTION_REG
	BANK0
	MOVLW	.255
	MOVWF	TMR0
	BCF	INTCON,T0IF
WAIT_TIMER_I2C
	BTFSS	INTCON,T0IF
	GOTO	WAIT_TIMER_I2C
	BCF	INTCON,T0IF
	BANK1
	MOVLW	B'00000111'
	MOVWF	OPTION_REG
	BANK0
	RETURN

; DELAY DE 10ms
DELAY_10
	MOVLW	.60
	MOVWF	TMR0
	BCF	INTCON,T0IF
WAIT_TIMER
	BTFSS	INTCON,T0IF
	GOTO	WAIT_TIMER
	BCF	INTCON,T0IF
	RETURN

; START DO PROTOCOLO I2C
I2C_START
	CALL	SDA_RELEASE	;SDA HIGH
	CALL	DELAY_I2C
	CALL	SCL_RELEASE	;SCL HIGH
	CALL	DELAY_I2C
	CALL	SDA_LOW		;SDA VAI PARA LOW ENQUANTO SCL EST¡ EM HIGH
	CALL	DELAY_I2C
	CALL	SCL_LOW
	CALL	DELAY_I2C
	RETURN
	
; STOP DO PROTOCOLO I2C
I2C_STOP
	CALL	SDA_LOW		;SDA LOW
	CALL	DELAY_I2C
	CALL	SCL_RELEASE	;SCL HIGH
	CALL	DELAY_I2C
	CALL	SDA_RELEASE	;SDA VAI PARA HIGH ENQUANTO SCL EST¡ EM HIGH
	CALL	DELAY_I2C
	CALL	SCL_LOW
	CALL	DELAY_I2C
	RETURN
	
; ESCREVE UM BYTE PELO PROTOCOLO I2C
; O BYTE A SER ESCRITO … O QUE ESTIVER EM I2C_BYTE
I2C_WRITE_BYTE
	MOVLW	.8
	MOVWF	COUNT
	
WRITE_LOOP
	BTFSS	I2C_BYTE,7
	GOTO	WRITE_BIT_0
	GOTO	WRITE_BIT_1

WRITE_BIT_0
	CALL	SDA_LOW
	GOTO	WRITE_CONTINUE
	
WRITE_BIT_1
	CALL	SDA_RELEASE
	
WRITE_CONTINUE
	CALL	DELAY_I2C
	CALL	SCL_RELEASE
	CALL	DELAY_I2C
	CALL	DELAY_I2C
	CALL	SCL_LOW
	CALL	DELAY_I2C
	RLF	I2C_BYTE
	DECFSZ	COUNT,F
	GOTO	WRITE_LOOP
	
	;ACK
	CALL	SDA_RELEASE
	CALL	DELAY_I2C
	CALL	SCL_RELEASE
	CALL	DELAY_I2C
WAIT_WRITE_ACK
	BTFSC	SDA
	GOTO	WAIT_WRITE_ACK
	CALL	DELAY_I2C
	CALL	SCL_LOW
	CALL	DELAY_I2C
	RETURN
	
; L  1 BYTE PELO PROTOCOLO I2C E ARMAZENA EM I2C_BYTE
I2C_READ_BYTE
	CALL	SDA_RELEASE
	
	MOVLW	.8
	MOVWF	COUNT

READ_LOOP
	RLF	I2C_BYTE
	CALL	DELAY_I2C
	CALL	SCL_RELEASE
	CALL	DELAY_I2C
	BTFSS	SDA
	GOTO	READ_BIT_0
	GOTO	READ_BIT_1
	
READ_BIT_0
	BCF	I2C_BYTE,0
	GOTO	READ_CONTINUE
	
READ_BIT_1
	BSF	I2C_BYTE,0
	
READ_CONTINUE
	CALL	SCL_LOW
	CALL	DELAY_I2C
	DECFSZ	COUNT
	GOTO	READ_LOOP
	
	;NACK
	CALL	SCL_RELEASE
	CALL	DELAY_I2C
	CALL	SCL_LOW
	CALL	DELAY_I2C
	
	RETURN

